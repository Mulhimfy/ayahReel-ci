"""Bakes the invite story card's two pictures into Dart.

A Shorebird patch carries Dart, never new asset files, and the story
card is the kind of thing that gets re-laid-out between store builds.
So the icon and the screen ship as base64 constants in
lib/render/invite_story_images.dart, generated from docs/store/invite/.

    python tool/invite_story_images.py
"""
import base64, io, pathlib
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
src = root / 'docs' / 'store' / 'invite'
out = root / 'lib' / 'render' / 'invite_story_images.dart'

def png(path, size):
    im = Image.open(path).convert('RGB').resize((size, size), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'PNG', optimize=True); return b.getvalue()

def jpg(path, width, quality):
    im = Image.open(path).convert('RGB')
    im = im.resize((width, round(im.height * width / im.width)), Image.LANCZOS)
    b = io.BytesIO(); im.save(b, 'JPEG', quality=quality, optimize=True); return b.getvalue()

icon = png(src / 'app_icon_384.png', 256)
screen = jpg(src / 'screenshot_640.jpg', 480, 80)

def const(name, data):
    s = base64.b64encode(data).decode()
    lines = [s[i:i + 76] for i in range(0, len(s), 76)]
    body = '\n'.join(f"    '{l}'" for l in lines)
    return f"const {name} =\n{body};\n"

out.write_text(
    "// GENERATED by tool/invite_story_images.py. Do not edit.\n"
    "//\n"
    "// The invite story card's pictures, as Dart rather than assets, so a\n"
    "// Shorebird patch can carry them: a patch ships code and never a new\n"
    "// file under assets/. Sources live in docs/store/invite/.\n\n"
    f"/// The app icon, {len(icon)} bytes of PNG at 256px.\n"
    + const('kInviteIconPng', icon)
    + f"\n/// One screen of the app, {len(screen)} bytes of JPEG at 480px wide.\n"
    + const('kInviteScreenJpg', screen),
    newline='\n')
print(out, len(icon), len(screen))
