import Foundation

/// Which verse and which picture the widget carries right now.
///
/// A word-for-word port of `QuranVerses` in lib/data/quran_verses.dart
/// — the same epoch, the same half-day count, the same Friday rule — so
/// the widget and the card in the app always agree, without the app
/// ever having to be opened. Two verses a day: one from midnight, one
/// from noon. Friday is the Salawat verse all day and is left out of
/// the count, so nothing in the rotation is skipped over by it. The
/// picture turns on a count of its own that does include Friday, so
/// Friday and Saturday never share one.
///
/// Any change to the arithmetic has to be made in all three places
/// (Dart, VerseSchedule.kt, and here). The list itself is
/// quran_verses.json in this target, generated by tool/quran_verses.py,
/// and the app's tests refuse a build where it differs from the Dart
/// list.
struct VerseSchedule {
  struct Verse: Decodable {
    let surah: Int
    let start: Int
    let end: Int
    let surahName: String
    let surahNameAr: String
    let arabic: String
    let shown: String
    let translation: String

    /// `ayahreel://verse/2/152` — what a tap opens the app with.
    var link: URL {
      let path = start == end ? "\(surah)/\(start)" : "\(surah)/\(start)/\(end)"
      return URL(string: "ayahreel://verse/\(path)")!
    }

    /// 'Al-Baqarah · 152', or 'البقرة · 152' — the caption.
    func reference(arabicUI: Bool) -> String {
      let name = arabicUI ? surahNameAr : surahName
      let range = start == end ? "\(start)" : "\(start)–\(end)"
      return "\(name) · \(range)"
    }
  }

  private struct Document: Decodable {
    let jumuah: Verse
    let verses: [Verse]
  }

  let jumuah: Verse
  let verses: [Verse]

  /// A Monday, long enough ago that no phone's clock is before it.
  static let epoch: Date = {
    var c = DateComponents()
    c.year = 2000; c.month = 1; c.day = 3
    return VerseSchedule.calendar.date(from: c)!
  }()

  static let perDay = 2

  /// The phone's own calendar and zone: "today" and "Friday" are the
  /// user's, as they are for the card in the app.
  static var calendar: Calendar {
    var c = Calendar(identifier: .gregorian)
    c.timeZone = TimeZone.current
    return c
  }

  /// The bundled list, read once per process.
  static let shared: VerseSchedule = {
    guard let url = Bundle.main.url(forResource: "quran_verses", withExtension: "json"),
      let data = try? Data(contentsOf: url),
      let doc = try? JSONDecoder().decode(Document.self, from: data)
    else {
      fatalError("quran_verses.json is missing from the widget bundle")
    }
    return VerseSchedule(jumuah: doc.jumuah, verses: doc.verses)
  }()

  func isJumuah(_ now: Date) -> Bool {
    VerseSchedule.calendar.component(.weekday, from: now) == 6
  }

  /// Calendar days since the epoch, never negative.
  func daysSinceEpoch(_ now: Date) -> Int {
    let cal = VerseSchedule.calendar
    let from = cal.startOfDay(for: VerseSchedule.epoch)
    let to = cal.startOfDay(for: now)
    let days = cal.dateComponents([.day], from: from, to: to).day ?? 0
    return max(0, days)
  }

  /// 0 before noon, 1 from noon.
  func halfOf(_ now: Date) -> Int {
    VerseSchedule.calendar.component(.hour, from: now) < 12 ? 0 : 1
  }

  /// Every half of every non-Friday day since the epoch, counted.
  func rotationSlot(_ now: Date) -> Int {
    let days = daysSinceEpoch(now)
    let fridays = (days + 2) / 7
    return (days - fridays) * VerseSchedule.perDay + halfOf(now)
  }

  /// Every half-day, Fridays included: the picture's count.
  func backgroundSlot(_ now: Date) -> Int {
    daysSinceEpoch(now) * VerseSchedule.perDay + halfOf(now)
  }

  func verse(at now: Date) -> Verse {
    isJumuah(now) ? jumuah : verses[rotationSlot(now) % verses.count]
  }

  /// Which of the `count` bundled pictures is up.
  func background(at now: Date, count: Int) -> Int {
    backgroundSlot(now) % count
  }

  /// When the verse after `now`'s takes over: noon, or midnight.
  func nextTurn(after now: Date) -> Date {
    let cal = VerseSchedule.calendar
    let today = cal.startOfDay(for: now)
    if cal.component(.hour, from: now) < 12 {
      // Noon on the clock, not twelve hours after midnight: on the days
      // the clocks change those are 11:00 or 13:00.
      return cal.date(bySettingHour: 12, minute: 0, second: 0, of: today)
        ?? cal.date(byAdding: .hour, value: 12, to: today)!
    }
    return cal.date(byAdding: .day, value: 1, to: today)!
  }
}
