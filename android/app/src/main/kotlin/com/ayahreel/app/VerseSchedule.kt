package com.ayahreel.app

import android.content.Context
import org.json.JSONObject
import java.time.DayOfWeek
import java.time.LocalDate
import java.time.LocalDateTime
import java.time.temporal.ChronoUnit

/**
 * Which verse and which picture the widget carries right now.
 *
 * A word-for-word port of `QuranVerses` in lib/data/quran_verses.dart
 * — the same epoch, the same half-day count, the same Friday rule — so
 * the widget and the card in the app always agree, without the app
 * ever having to be opened. Two verses a day: one from midnight, one
 * from noon. Friday is the Salawat verse all day and is left out of
 * the count, so nothing in the rotation is skipped over by it. The
 * picture turns on a count of its own that does include Friday, so
 * Friday and Saturday never share one.
 *
 * Any change to the arithmetic has to be made in all three places
 * (Dart, here, and VerseSchedule.swift). The list itself is
 * assets/quran_verses.json, generated by tool/quran_verses.py, and the
 * app's tests refuse a build where it differs from the Dart list.
 */
class VerseSchedule private constructor(
    val jumuah: Verse,
    val verses: List<Verse>,
) {
    class Verse(
        val surah: Int,
        val start: Int,
        val end: Int,
        val surahName: String,
        val surahNameAr: String,
        val arabic: String,
        val shown: String,
        val translation: String,
    ) {
        /** `ayahreel://verse/2/152` — what a tap opens the app with. */
        val link: String
            get() = if (start == end) "ayahreel://verse/$surah/$start"
            else "ayahreel://verse/$surah/$start/$end"

        /** 'Al-Baqarah · 152', or 'البقرة · 152' — the caption. */
        fun reference(arabicUi: Boolean): String {
            val name = if (arabicUi) surahNameAr else surahName
            val range = if (start == end) "$start" else "$start–$end"
            return "$name · $range"
        }
    }

    fun isJumuah(now: LocalDateTime): Boolean = now.dayOfWeek == DayOfWeek.FRIDAY

    /** Calendar days since the epoch, never negative. */
    fun daysSinceEpoch(now: LocalDateTime): Long =
        ChronoUnit.DAYS.between(EPOCH, now.toLocalDate()).coerceAtLeast(0)

    /** 0 before noon, 1 from noon. */
    fun halfOf(now: LocalDateTime): Int = if (now.hour < 12) 0 else 1

    /** Every half of every non-Friday day since the epoch, counted. */
    fun rotationSlot(now: LocalDateTime): Long {
        val days = daysSinceEpoch(now)
        val fridays = (days + 2) / 7
        return (days - fridays) * PER_DAY + halfOf(now)
    }

    /** Every half-day, Fridays included: the picture's count. */
    fun backgroundSlot(now: LocalDateTime): Long = daysSinceEpoch(now) * PER_DAY + halfOf(now)

    fun verseAt(now: LocalDateTime): Verse =
        if (isJumuah(now)) jumuah else verses[(rotationSlot(now) % verses.size).toInt()]

    /** Which of the [count] bundled pictures is up. */
    fun backgroundAt(now: LocalDateTime, count: Int): Int =
        (backgroundSlot(now) % count).toInt()

    /** When the verse after [now]'s takes over: noon, or midnight. */
    fun nextTurn(now: LocalDateTime): LocalDateTime {
        val today = now.toLocalDate()
        return if (now.hour < 12) today.atTime(12, 0) else today.plusDays(1).atStartOfDay()
    }

    companion object {
        /** A Monday, long enough ago that no phone's clock is before it. */
        val EPOCH: LocalDate = LocalDate.of(2000, 1, 3)
        const val PER_DAY = 2

        @Volatile
        private var cached: VerseSchedule? = null

        /** The bundled list, read once per process. */
        fun load(context: Context): VerseSchedule {
            cached?.let { return it }
            val json = context.assets.open("quran_verses.json").bufferedReader().use { it.readText() }
            val doc = JSONObject(json)
            fun verse(o: JSONObject) = Verse(
                surah = o.getInt("surah"),
                start = o.getInt("start"),
                end = o.getInt("end"),
                surahName = o.getString("surahName"),
                surahNameAr = o.getString("surahNameAr"),
                arabic = o.getString("arabic"),
                shown = o.getString("shown"),
                translation = o.getString("translation"),
            )
            val list = doc.getJSONArray("verses")
            val schedule = VerseSchedule(
                jumuah = verse(doc.getJSONObject("jumuah")),
                verses = List(list.length()) { verse(list.getJSONObject(it)) },
            )
            cached = schedule
            return schedule
        }
    }
}
